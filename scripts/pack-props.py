"""Pack generated props, creatures and enemies (art/generated/*.png with transparency) into
dist/assets/props.webp + props-layout.mjs, and add their small icons to the item atlas.
Usage: python3 scripts/pack-props.py   (needs Pillow)"""
from PIL import Image
from pathlib import Path
import importlib.util,json
root=Path(__file__).resolve().parents[1];gen=root/'art/generated';assets=root/'dist/assets'
spec=importlib.util.spec_from_file_location('imp',root/'scripts/import-art.py');imp=importlib.util.module_from_spec(spec);spec.loader.exec_module(imp)
# name: (file, longest side in the atlas). Larger sprites keep detail on high-density phone screens.
PROPS={'stump':('prop-stump',240),'greenhouse':('prop-greenhouse',560),'purifier':('prop-purifier',220),'fox':('creature-fox',190),
 'crate':('prop-crate',180),'ore':('prop-ore',210),'generator':('prop-generator',200),'lift':('prop-lift',260),'filter':('prop-filter',220),
 'metro':('prop-metro',300),'workbench':('prop-workbench',260),'salamander':('enemy-salamander',300),'deer':('enemy-deer',420),'armadillo':('enemy-armadillo',300)}
def load(name):
    im=imp.clean(Image.open(gen/f'{name}.png').convert('RGBA'));return im.crop(im.getbbox())
sprites={}
for k,(f,side) in PROPS.items():
    im=load(f);s=side/max(im.size);sprites[k]=im.resize((max(1,round(im.width*s)),max(1,round(im.height*s))),Image.Resampling.LANCZOS)
    a=sprites[k].getchannel('A').point(lambda v:255 if v>110 else 0);sprites[k].putalpha(a)
# Shelf packing, tallest first.
W=1024;order=sorted(sprites,key=lambda k:-sprites[k].height);x=y=row=0;pos={}
for k in order:
    im=sprites[k]
    if x+im.width+2>W:x=0;y+=row+2;row=0
    pos[k]=(x,y,im.width,im.height);x+=im.width+2;row=max(row,im.height)
H=y+row;sheet=Image.new('RGBA',(W,H))
for k,(x,y,w,h) in pos.items():sheet.alpha_composite(sprites[k],(x,y))
sheet.save(assets/'props.webp',quality=90,method=6)
(assets/'props-layout.mjs').write_text('// Generated by scripts/pack-props.py: sprite boxes in props.webp.\nexport default '+json.dumps({k:dict(x=v[0],y=v[1],w=v[2],h=v[3]) for k,v in pos.items()},separators=(',',':'))+';\n')
print('props.webp',sheet.size,len(pos))
