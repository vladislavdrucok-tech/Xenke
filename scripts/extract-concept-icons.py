"""Cut item icons and portraits out of the owner's concept images (art/concepts-v06) into a
temporary game atlas, until dedicated item art is generated from docs/ART_BRIEFS_v06_UK.md.
Usage: python3 scripts/extract-concept-icons.py   (needs Pillow)"""
from PIL import Image
from collections import deque
from pathlib import Path
import json
root=Path(__file__).resolve().parents[1]
src={n:Image.open(root/f'art/concepts-v06/{n}.png').convert('RGB') for n in ('workbench','mine','vault')}
# id: (image, box in original pixels). Boxes sit inside slot frames; digits and bars are dropped as small parts.
ICONS={
 'wood':('workbench',(829,780,893,859)),'scrap':('workbench',(906,780,975,859)),'cloth':('workbench',(989,780,1058,859)),
 'seed':('workbench',(1074,780,1143,859),'digits'),'stone':('workbench',(1156,780,1228,859)),
 'hammer':('workbench',(56,830,110,886)),'flashlight':('workbench',(127,826,190,890)),'bag':('workbench',(203,826,267,890)),
 'medkit':('workbench',(283,826,342,890)),'canteen':('workbench',(360,826,421,890)),
 'torch':('workbench',(833,313,892,407)),'planter':('workbench',(828,553,921,632)),'pickaxe':('workbench',(842,662,927,742)),
 'filter':('workbench',(1108,385,1308,602)),
 'axe':('mine',(590,822,650,884)),'bottle':('mine',(750,815,830,898)),'can':('mine',(843,815,918,898)),
 'ore':('mine',(1020,822,1098,898),'digits'),'gear':('mine',(1108,815,1193,898)),
 'scanner':('vault',(752,820,814,902)),'capsule':('vault',(848,820,905,902)),'rope':('vault',(938,820,998,902)),
}
PORTRAITS={'einstein':('vault',(22,17,106,108))}
def cutout(img,box,digits=False,tol=42):
    c=img.crop(box).convert('RGBA');w,h=c.size;px=c.load()
    # Stack counts are near-white digits in the lower right corner; clear them before keying.
    if digits:
        for x in range(int(w*.6),w):
            for y in range(int(h*.6),h):
                r,g,b,_=px[x,y]
                if min(r,g,b)>150 and max(r,g,b)-min(r,g,b)<40:px[x,y]=(0,0,0,0)
    border=[px[x,0] for x in range(w)]+[px[x,h-1] for x in range(w)]+[px[0,y] for y in range(h)]+[px[w-1,y] for y in range(h)]
    bg=sorted(border,key=lambda p:p[0]+p[1]+p[2])[len(border)//2]
    near=lambda p:p[3]==0 or sum((p[i]-bg[i])**2 for i in range(3))<tol*tol or max(p[:3])<34
    seen=[[False]*h for _ in range(w)];q=deque()
    for x in range(w):q.extend([(x,0),(x,h-1)])
    for y in range(h):q.extend([(0,y),(w-1,y)])
    while q:
        x,y=q.popleft()
        if x<0 or y<0 or x>=w or y>=h or seen[x][y]:continue
        seen[x][y]=True
        if not near(px[x,y]):continue
        px[x,y]=(0,0,0,0);q.extend([(x+1,y),(x-1,y),(x,y+1),(x,y-1)])
    # Keep only big connected parts: slot numbers, counts and durability bars are small islands.
    comp=[[-1]*h for _ in range(w)];sizes=[]
    for sx in range(w):
        for sy in range(h):
            if px[sx,sy][3]==0 or comp[sx][sy]>=0:continue
            n=len(sizes);cnt=0;q=deque([(sx,sy)]);comp[sx][sy]=n
            while q:
                x,y=q.popleft();cnt+=1
                for nx,ny in((x+1,y),(x-1,y),(x,y+1),(x,y-1)):
                    if 0<=nx<w and 0<=ny<h and comp[nx][ny]<0 and px[nx,ny][3]:comp[nx][ny]=n;q.append((nx,ny))
            sizes.append(cnt)
    keep={i for i,s in enumerate(sizes) if s>=max(sizes)*0.12}
    for x in range(w):
        for y in range(h):
            if px[x,y][3] and comp[x][y] not in keep:px[x,y]=(0,0,0,0)
    return c.crop(c.getbbox())
CELL=96
ids=list(ICONS);cols=8;rows=(len(ids)+cols-1)//cols
sheet=Image.new('RGBA',(cols*CELL,rows*CELL));layout={}
for i,k in enumerate(ids):
    im=cutout(src[ICONS[k][0]],ICONS[k][1],len(ICONS[k])>2)
    if max(im.size)>CELL-4:im.thumbnail((CELL-4,CELL-4),Image.Resampling.LANCZOS)
    x,y=i%cols*CELL+(CELL-im.width)//2,i//cols*CELL+(CELL-im.height)//2
    sheet.alpha_composite(im,(x,y));layout[k]=i
out=root/'dist/assets';sheet.save(out/'items.webp',lossless=True,method=6)
for k,(n,box) in PORTRAITS.items():src[n].crop(box).resize((84,91),Image.Resampling.NEAREST).save(out/f'portrait-{k}.webp',lossless=True)
(out/'items-layout.mjs').write_text('// Generated by scripts/extract-concept-icons.py: index of each icon in items.webp (8 columns of 96 px).\nexport default '+json.dumps({'cell':CELL,'cols':cols,'rows':rows,'index':layout})+';\n')
print(sheet.size,len(ids),'icons')
